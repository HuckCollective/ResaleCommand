/**
 * Sanitizes historical SKU -> UPC map, dropping corrupted entries like `"0EJ07M": "HUCK-"`.
 */
export function sanitizeHistoricalSkuMappings(rawMap = RAW_HISTORICAL_MD_SKU_TO_UPC) {
    const sanitized = {};
    for (const [rawSku, rawUpc] of Object.entries(rawMap)) {
        const sku = String(rawSku || '').trim().toUpperCase();
        const upc = String(rawUpc || '').trim().toUpperCase();
        if (!/^0EJ[0-9A-Z]{3}$/i.test(sku)) continue;
        // Explicitly reject incomplete/corrupted barcode prefixes such as "HUCK-" on 0EJ07M
        if (!/^(?:HUCK|PDXGL)-[0-9]{3,6}$/i.test(upc)) continue;
        sanitized[sku] = upc;
    }
    return sanitized;
}

async function seedMdBoothSkus() {
    const endpoint = process.env.PUBLIC_APPWRITE_ENDPOINT || 'https://sfo.cloud.appwrite.io/v1';
    const projectId = process.env.PUBLIC_APPWRITE_PROJECT_ID || '69714b35003a8adab6bb';
    const apiKey = process.env.APPWRITE_API_KEY || '';
    const dbId = process.env.PUBLIC_APPWRITE_DB_ID || 'resale_db';
    const itemsCol = process.env.PUBLIC_APPWRITE_ITEMS_COLLECTION_ID || 'items';

    if (!apiKey) {
        console.error('❌ Missing APPWRITE_API_KEY environment variable. Run with --env-file=.env');
        process.exit(1);
    }

    const client = new Client().setEndpoint(endpoint).setProject(projectId).setKey(apiKey);
    const databases = new Databases(client);
    const sanitizedMap = sanitizeHistoricalSkuMappings();
    const entries = Object.entries(sanitizedMap);

    console.log(`🌱 Seeding ${entries.length} sanitized 0EJxxx -> HUCK/PDXGL mappings into Appwrite (${dbId}.${itemsCol})...`);

    const docByUpc = new Map();
    let cursor = null;
    for (let page = 0; page < 30; page++) {
        const queries = [Query.limit(100), Query.orderDesc('$id')];
        if (cursor) queries.push(Query.cursorAfter(cursor));
        const res = await databases.listDocuments(dbId, itemsCol, queries);
        const docs = res.documents || [];
        for (const doc of docs) {
            const upc = String(doc.barcode || doc.upc || '').trim().toUpperCase();
            if (upc && !docByUpc.has(upc)) {
                docByUpc.set(upc, doc);
            }
        }
        if (docs.length < 100) break;
        cursor = docs[docs.length - 1].$id;
    }

    let updated = 0;
    let skipped = 0;
    for (const [boothSku, upc] of entries) {
        const targetDoc = docByUpc.get(upc);
        if (!targetDoc) {
            skipped++;
            continue;
        }
        const existingSku = String(targetDoc.external_sku || targetDoc.locationSku || '').trim().toUpperCase();
        if (existingSku === boothSku) {
            skipped++;
            continue;
        }
        try {
            await databases.updateDocument(dbId, itemsCol, targetDoc.$id, {
                locationSku: boothSku,
                external_sku: boothSku,
            });
            updated++;
        } catch {
            try {
                await databases.updateDocument(dbId, itemsCol, targetDoc.$id, {
                    locationSku: boothSku,
                });
                updated++;
            } catch (err) {
                console.warn(`⚠️ Failed to seed ${boothSku} -> ${upc}:`, err?.message || err);
            }
        }
    }

    console.log(`✅ Completed Appwrite booth SKU seed: ${updated} updated, ${skipped} already linked or skipped.`);
}

if (import.meta.url === `file://${process.argv[1]?.replace(/\\/g, '/')}`) {
    seedMdBoothSkus().catch(err => {
        console.error('❌ Seed script failed:', err);
        process.exit(1);
    });
}

